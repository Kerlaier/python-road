# ============================================================
# 小结
# ============================================================
# ┌──────────────────┬──────────────────────────────┐
# │ 操作              │ 写法                          │
# ├──────────────────┼──────────────────────────────┤
# │ 打开（推荐）       │ with open("文件名", "模式") as f: │
# │ 读全部             │ f.read()                    │
# │ 读一行             │ f.readline()                │
# │ 按行读             │ for line in f:              │
# │ 写                 │ f.write("内容")             │
# │ CSV写             │ writer = csv.writer(f)       │
# │                   │ writer.writerow([...])       │
# │ CSV读             │ reader = csv.reader(f)       │
# │                   │ for row in reader:           │
# └──────────────────┴──────────────────────────────┘
#
# 一句话：open 打开 → 读写 → 自动 close（用 with），数据就能永久保存。
