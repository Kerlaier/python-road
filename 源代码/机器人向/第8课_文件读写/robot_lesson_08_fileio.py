# ============================================================
# 一、为什么需要文件？
# ============================================================
# 之前的程序，数据全在内存里，程序一关就没了。
# 机器人跑了1000小时的数据，总不能靠打印屏幕来保存。

# 文件 = 程序的"硬盘存储"，关机不丢。
# 常见场景：
#   传感器日志 → 写入 robot_log.csv
#   配置文件   → 读取 config.txt
#   错误记录   → 追加 error.log


# ============================================================
# 二、打开文件 —— open()
# ============================================================
# 语法公式：
#   f = open("文件名", "模式")     ← 打开文件，返回文件对象
#   f.write(...) 或 f.read(...)   ← 读或写
#   f.close()                     ← 用完后关闭！

# 模式（记住三个就够）：
#   "r"  → read   只读，文件必须存在
#   "w"  → write  只写，文件不存在就新建，存在就清空重写
#   "a"  → append 追加，文件不存在就新建，存在就在末尾接着写

# 先看例子，再解释：
f = open("test.txt", "w")     # 以"写"模式打开（没有就新建）
f.write("hello")              # 往文件里写入
f.close()                     # 关闭文件，数据才真正落盘

# 上面三行 = 打开 → 写入 → 关闭，三步缺一不可。

# 验证：用"读"模式打开
f = open("test.txt", "r")     # 以"读"模式打开
content = f.read()            # 读取全部内容
f.close()
print(content)                # 输出: hello


# ============================================================
# 三、更安全的写法 —— with（推荐！）
# ============================================================
# 手动 close() 容易忘。with 语句自动帮你关：
# 语法公式：
#   with open("文件名", "模式") as f:
#       读写操作...

with open("test.txt", "r") as f:
    data = f.read()
    # 出了这个缩进，文件自动关闭
print(data)                   # 输出: hello

# 以后一律用 with，不用手动 close()


# ============================================================
# 四、读文件的三种方式
# ============================================================

# 先准备一个多行文件做演示
with open("test.txt", "w") as f:
    f.write("第一行\n第二行\n第三行")    # \n 是换行符

# 4.1 read() —— 一次性读全部，适合小文件
with open("test.txt", "r") as f:
    all_text = f.read()        # 返回一个整个字符串
print("read():", all_text)     # 输出: 第一行\n第二行\n第三行

# 4.2 readlines() —— 按行读，返回列表，适合逐行处理
with open("test.txt", "r") as f:
    lines = f.readlines()      # 返回 ["第一行\n", "第二行\n", "第三行"]
for line in lines:
    print("行内容:", line.strip())  # strip() 去掉首尾空白和换行

# 4.3 直接 for 循环文件对象 —— 逐行读，最省内存
with open("test.txt", "r") as f:
    for line in f:             # 文件对象本身可被 for 遍历！
        print("遍历:", line.strip())

print()


# ============================================================
# 五、实战一：机器人日志写入（写模式）
# ============================================================
# 场景：机器人巡检，每秒记录时间、位置、温度，写入 CSV 文件

import csv

# 模拟巡检数据
log_data = [
    ["时间",   "X坐标", "Y坐标", "温度"],
    ["08:00",  "0.0",   "0.0",   "36.5"],
    ["08:01",  "1.2",   "2.1",   "36.8"],
    ["08:02",  "2.5",   "4.0",   "37.1"],
    ["08:03",  "3.8",   "5.7",   "37.5"],
]

# 写入 robot_log.csv
with open("robot_log.csv", "w", newline="", encoding="utf-8-sig") as f:
    writer = csv.writer(f)                      # 创建 CSV 写入器
    for row in log_data:                        # 一行一行写
        writer.writerow(row)

print("robot_log.csv 写入完成！")

# 运行后，去桌面 python学习文件 文件夹打开 robot_log.csv 看看


# ============================================================
# 六、实战二：读取日志并分析（读模式）
# ============================================================

with open("robot_log.csv", "r", encoding="utf-8-sig") as f:
    reader = csv.reader(f)       # 创建 CSV 读取器
    header = next(reader)        # next() 拿第一行（表头）
    print("表头:", header)

    temps = []                   # 收集所有温度
    for row in reader:
        temp = float(row[3])     # 第4列（索引3）是温度，转成数字
        temps.append(temp)
        print(f"  时间 {row[0]} → 温度 {temp}°C")

    avg_temp = sum(temps) / len(temps)   # 平均温度
    print(f"\n平均温度: {avg_temp:.1f}°C")

print()


# ============================================================
# 七、实战三：追加模式（a）—— 日志持续写入
# ============================================================
# 场景：机器人运行中持续记录，不想覆盖之前的日志

with open("robot_log.csv", "a", newline="", encoding="utf-8-sig") as f:
    writer = csv.writer(f)
    writer.writerow(["08:04", "4.5", "7.0", "37.8"])   # 追加一行
    writer.writerow(["08:05", "5.0", "8.2", "38.0"])

print("追加了2行日志！")
print()

# ============================================================
# 八、三种模式对比（重要！）
# ============================================================
# ┌────────┬──────────────┬────────────────────┐
# │ 模式    │ 文件不存在    │ 文件存在            │
# ├────────┼──────────────┼────────────────────┤
# │ "r"    │ 报错 ❌       │ 从头读              │
# │ "w"    │ 新建 ✅       │ 清空后从头写 ⚠️     │
# │ "a"    │ 新建 ✅       │ 末尾接着写 ✅        │
# └────────┴──────────────┴────────────────────┘


