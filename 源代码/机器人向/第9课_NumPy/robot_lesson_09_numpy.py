# ============================================================
# 六、实战：机械臂旋转矩阵（正运动学核心）
# ============================================================
# 场景：机械臂末端从 (x, y) 位置，绕原点旋转 θ 角度
# 旋转矩阵公式：
#   [x']   [cosθ  -sinθ] [x]
#   [y'] = [sinθ   cosθ] [y]
#
# 即：新坐标 = 旋转矩阵 × 原坐标

# 机械臂末端当前位置
pos = np.array([1.0, 0.0])     # 坐标 (1, 0)，即正右方水平

# 旋转 90°（转为弧度：90° = π/2）
theta = np.radians(90)          # degrees → radians，90° → 1.5708 弧度

# 旋转矩阵
rot = np.array([
    [np.cos(theta), -np.sin(theta)],   # 第一行
    [np.sin(theta),  np.cos(theta)]    # 第二行
])

# 矩阵乘法：旋转矩阵 @ 原坐标 = 新坐标
new_pos = rot @ pos              # @ 是矩阵乘法符号，后面解释

print(f"原坐标: ({pos[0]:.1f}, {pos[1]:.1f})")
print(f"旋转90°后: ({new_pos[0]:.1f}, {new_pos[1]:.1f})")
# 输出: 原坐标: (1.0, 0.0) → 旋转90°后: (0.0, 1.0)
# (1,0) 逆时针转 90° 到 (0,1)，符合直觉！

print()


# ============================================================
# 七、@ 运算符 —— 矩阵乘法
# ============================================================
# NumPy 的 @ 做线性代数中的矩阵乘法（不是逐元素相乘）

A = np.array([[1, 2],
              [3, 4]])
B = np.array([[5, 6],
              [7, 8]])

print("A * B (逐元素):\n", A * B)    # 1*5=5  2*6=12  3*7=21 4*8=32
print("A @ B (矩阵乘法):\n", A @ B)  # [[1*5+2*7, 1*6+2*8], [3*5+4*7, 3*6+4*8]]
#                                   # = [[19, 22], [43, 50]]

print()


# ============================================================
# 八、实战：批量坐标变换
# ============================================================
# 场景：机械臂末端途径 4 个路径点，全部旋转 45°

# 路径点：每个点一行 (x, y)，组成 4×2 矩阵
path = np.array([
    [1.0, 0.0],
    [2.0, 0.5],
    [3.0, 1.0],
    [2.5, 1.5]
])

theta = np.radians(45)
rot45 = np.array([
    [np.cos(theta), -np.sin(theta)],
    [np.sin(theta),  np.cos(theta)]
])

# 批量变换：path @ rot45.T  （.T 是转置，为了让矩阵形状匹配）
# 等价于每个点分别做 rot45 @ [x, y]
transformed = (rot45 @ path.T).T   # 先转置做乘法，再转回来

print("旋转45°后的路径点:")
for i in range(len(path)):
    print(f"  点{i+1}: ({path[i,0]:.1f}, {path[i,1]:.1f}) → "
          f"({transformed[i,0]:.1f}, {transformed[i,1]:.1f})")

print()


# ============================================================
# 九、常用统计函数
# ============================================================

data = np.array([36.5, 38.2, 37.0, 42.1, 36.8])

print(f"平均值: {np.mean(data):.1f}")   # 输出: 38.1  (跟 sum/len 一样)
print(f"最大值: {np.max(data)}")         # 输出: 42.1
print(f"最小值: {np.min(data)}")         # 输出: 36.5
print(f"标准差: {np.std(data):.2f}")     # 输出: 2.06  (数据波动程度)
print(f"总和:   {np.sum(data)}")         # 输出: 190.6

print()


