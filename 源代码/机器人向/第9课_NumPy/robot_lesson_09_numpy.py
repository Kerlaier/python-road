# 四、常用创建函数
# ============================================================

# np.zeros(n)     —— 创建 n 个 0 的数组
print("zeros:", np.zeros(5))    # 输出: [0. 0. 0. 0. 0.]

# np.ones(n)      —— 创建 n 个 1 的数组
