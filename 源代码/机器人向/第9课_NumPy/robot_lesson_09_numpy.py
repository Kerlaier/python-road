# ============================================================
# 一、为什么需要 NumPy？
# ============================================================
# Python 的 list 能做很多事，但遇到大量数据就慢了。
# NumPy 的 array（数组）专门为数值计算优化，比 list 快几十倍。

# 语法公式：
#   数组名 = np.array(列表)

# 对比：
py_list = [1, 2, 3]            # 普通列表
np_arr  = np.array([1, 2, 3])  # NumPy 数组

print("列表:", py_list)         # 输出: [1, 2, 3]
print("数组:", np_arr)          # 输出: [1 2 3]   ← 注意：没逗号！

print()


# ============================================================
# 二、数组运算 —— 跟列表最大的不同
# ============================================================

# 列表 + 列表 = 拼接
a = [1, 2, 3]
b = [4, 5, 6]
print(a + b)                    # 输出: [1, 2, 3, 4, 5, 6]  拼接了

# 数组 + 数组 = 逐元素相加  ← 这才是数学运算！
a_arr = np.array([1, 2, 3])
b_arr = np.array([4, 5, 6])
print(a_arr + b_arr)            # 输出: [5 7 9]   1+4=5, 2+5=7, 3+6=9
print(a_arr * b_arr)            # 输出: [4 10 18] 1*4=4, 2*5=10, 3*6=18
print(a_arr * 2)                # 输出: [2 4 6]   每个元素都乘2
print(a_arr ** 2)               # 输出: [1 4 9]   每个元素平方

print()


# ============================================================
# 三、机械臂场景：传感器读数批量处理
# ============================================================
# 6 个温度传感器，每秒读一次，所有读数同时转摄氏度→开尔文

