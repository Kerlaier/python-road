kelvin = celsius + 273.15       # 每个元素同时加，不用 for 循环！
print("开尔文温度:", kelvin)
# 输出: [309.65 311.35 310.15 315.25 310.95 310.65]

# 用列表做同样的事，得写循环：
# for t in celsius: ...    ← NumPy 一行搞定

