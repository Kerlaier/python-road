# ┌──────────┬────────────────────────────────────┐
# │ 操作      │ 写法                                │
# ├──────────┼────────────────────────────────────┤
# │ 创建      │ d = {"键": 值, ...}                 │
# │ 取值      │ d["键"]           ← 不存在会报错    │
# │ 安全取值  │ d.get("键", 默认)  ← 不存在返默认    │
# │ 添加/修改 │ d["键"] = 新值                      │
# │ 删        │ del d["键"] 或 d.pop("键")          │
# │ 遍历      │ for k, v in d.items():              │
# │ 查存在    │ if "键" in d:                       │
# └──────────┴────────────────────────────────────┘
