# ============================================================
# 一、为什么需要字典？
# ============================================================
# 场景：机器人有6个传感器，每秒返回一次温度。用列表当然能存：
temps = [36.5, 38.2, 37.0, 36.8, 42.1, 37.5]
# 问题来了：第3个温度是哪个传感器的？得记住索引 → 容易搞混。

# 字典用"名字"来找值，而不是用位置编号：
# 语法公式： 字典 = {键1: 值1, 键2: 值2, ...}
#            ↑ 键是标签（字符串/数字），值是要存的数据

sensors = {
    "头部": 36.5,
    "左臂": 38.2,
    "右臂": 37.0,
    "左腿": 36.8,
    "右腿": 42.1,
    "躯干": 37.5
}
# 想查右腿温度？直接用名字：
print(sensors["右腿"])            # 输出: 42.1
# 不用记"右腿是第几个"，字典帮你映射好了。

print()


# ============================================================
# 二、字典的基本操作
# ============================================================

# 2.1 创建字典
robot = {"name": "Atlas", "height": 150, "weight": 89}
print(robot)                       # 输出: {'name': 'Atlas', 'height': 150, 'weight': 89}

# 2.2 取值 —— 用键名
print(robot["name"])               # 输出: Atlas
print(robot["height"])             # 输出: 150

# 2.3 添加 / 修改 —— 直接赋值
robot["speed"] = 5                 # 添加新键值对
robot["weight"] = 85               # 修改已有键的值
print(robot)                       # 输出: {'name': 'Atlas', 'height': 150, 'weight': 85, 'speed': 5}

# 2.4 删除 —— del 或 pop()
del robot["speed"]                 # 干掉 speed 这个键
print(robot)                       # 输出: {'name': 'Atlas', 'height': 150, 'weight': 85}

print()


# ============================================================
# 三、安全取值 —— get()
# ============================================================
# robot["speed"]   ← 如果 speed 不存在，程序直接报错崩溃
# robot.get("speed")  ← 不存在返回 None，程序继续跑

print(robot.get("height"))         # 输出: 150  （存在，返回值）
print(robot.get("speed"))          # 输出: None （不存在，不报错）
print(robot.get("speed", 0))       # 输出: 0    （不存在，返回默认值 0）

print()


# ============================================================
# 四、遍历字典
# ============================================================

sensor_data = {"温度": 36.5, "湿度": 45.2, "气压": 1013}

# 4.1 遍历所有键 —— .keys()
print("传感器列表:")
for key in sensor_data.keys():
    print(f"  {key}")              # 输出: 温度 湿度 气压（每个一行）

# 4.2 遍历所有值 —— .values()
print("所有读数:")
for value in sensor_data.values():
    print(f"  {value}")            # 输出: 36.5 45.2 1013

# 4.3 同时遍历键和值 —— .items()  ← 最常用！
print("传感器 → 读数:")
for name, reading in sensor_data.items():
    print(f"  {name}: {reading}")  # 输出: 温度: 36.5 等

print()


# ============================================================
# 五、检查键是否存在 —— in
# ============================================================

if "温度" in sensor_data:
    print("温度传感器正常")         # ← 会执行

if "风速" not in sensor_data:
    print("没有安装风速传感器")     # ← 会执行

print()


# ============================================================
# 六、字典的实用方法
# ============================================================

# len() —— 几对键值
print(len(sensor_data))            # 输出: 3

# .pop(key) —— 删除并返回值
pressure = sensor_data.pop("气压")  # 删掉气压，返回 1013
print(pressure)                     # 输出: 1013
print(sensor_data)                  # 输出: {'温度': 36.5, '湿度': 45.2}

# .clear() —— 清空
backup = sensor_data.copy()        # 先备份
sensor_data.clear()
print(sensor_data)                  # 输出: {}

print()


# ============================================================
# 七、嵌套字典 —— 机器人真实场景
# ============================================================
# 一个机械臂有多个关节，每个关节有角度、速度、力矩：

arm = {
    "肩部": {"angle": 45, "speed": 30, "torque": 2.5},
    "肘部": {"angle": 90, "speed": 25, "torque": 1.8},
    "腕部": {"angle": 30, "speed": 40, "torque": 0.9}
}

# 取肘部角度：
print(arm["肘部"]["angle"])        # 输出: 90

# 遍历所有关节信息：
for joint, info in arm.items():
    print(f"{joint}: 角度={info['angle']}°, 速度={info['speed']}°/s")


print()


# ============================================================
# 八、实战：传感器异常检测
# ============================================================
# 场景：机器人巡检，发现温度 > 40 的传感器要报警

sensors = {"头部": 36.5, "左臂": 38.2, "右臂": 42.0, "左腿": 36.8, "右腿": 41.5}

print("异常传感器检测:")
for name, temp in sensors.items():
    if temp > 40:
        print(f"  ⚠️  {name}温度异常: {temp}°C")
    else:
        print(f"  ✅ {name}: {temp}°C")


print()


