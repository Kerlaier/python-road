# ========== 练习3：传感器数据管理 ==========
# 题干：
#   有一个传感器字典：
#   sensors = {"温度": 36.5, "湿度": 45.2, "气压": 1013}
#   请完成以下操作：
#     a. 添加一个 新传感器 "风速": 3.2
#     b. 修改 "温度" 为 37.1
#     c. 删除 "湿度"
#     d. 最后打印修改后的字典

# 提示：
#   添加/修改都是 d["键"] = 值（键存在就是改，不存在就是加）
#   删除用 del d["键"] 或 d.pop("键")

# ↓↓↓ 你的代码 ↓↓↓
sensors = {"温度": 36.5, "湿度": 45.2, "气压": 1013}
sensors['风速'] = 3.2
sensors['温度'] = 37.1
del sensors['湿度']
print(sensors)



# ========== 练习4：机器人巡检报警 ==========
# 题干：
#   机器人巡检工厂，下面是各电机温度：
#   motor_temps = {"电机A": 42, "电机B": 55, "电机C": 38, "电机D": 60, "电机E": 45}
#   遍历所有电机，温度 ≥ 50 的打印 "⚠️ XXX过热"，否则打印 "✅ XXX正常"

# 提示：
#   for name, temp in motor_temps.items():
#       if temp >= 50:
#           ...

# ↓↓↓ 你的代码 ↓↓↓
motor_temps = {"电机A": 42, "电机B": 55, "电机C": 38, "电机D": 60, "电机E": 45}
for a,b in motor_temps.items():
    if b >= 50:
        print(f" {a}过热 ")
    else:
        print(f"  {a}正常  ")    
    
